<?php

declare(strict_types=1);

namespace Config;

use CodeIgniter\Config\BaseConfig;

class Photos extends BaseConfig
{
    public string $faceUrl = 'http://127.0.0.1:8090';
    public string $serviceToken = '';
    public string $localEncryptionKey = '';
    public string $modelVersion = 'sface-2021dec-yunet-2023mar-v1';
    // Provisional cosine similarity, NOT a probability. Calibrate before production.
    public float $threshold = 0.55;
    public int $maxUploadBytes = 10485760;
    public int $maxPixels = 40000000;
    public int $maxBatch = 20;

    public function __construct()
    {
        parent::__construct();
        $this->faceUrl = rtrim((string) env('PHOTOS_FACE_URL', $this->faceUrl), '/');
        $this->serviceToken = (string) env('FACE_SERVICE_TOKEN', '');
        // Local development secrets are generated by photos:setup, never committed.
        $privateFile = WRITEPATH . 'photo-secrets.json';
        if (ENVIRONMENT !== 'testing' && (@lstat($privateFile) !== false || is_link($privateFile))) {
            $private = self::readPrivateSecrets($privateFile);
            if ($this->serviceToken === '') {
                $this->serviceToken = $private['service_token'];
            }
            // SelfieService prefers encryption.key. Changing either key does NOT
            // re-encrypt old selfies; retain the old key until migration or purge.
            $this->localEncryptionKey = $private['encryption_key'];
        }
        $threshold = filter_var(env('PHOTOS_MATCH_THRESHOLD', $this->threshold), FILTER_VALIDATE_FLOAT);
        if ($threshold === false || ! is_finite($threshold) || $threshold < -1 || $threshold > 1) {
            throw new \RuntimeException('Konfigurasi ambang pencarian foto tidak valid.');
        }
        $this->threshold = $threshold;
    }

    /** Internal setup/loader helper. Never render or log the returned secrets. */
    public static function readPrivateSecrets(string $path): array
    {
        $invalid = 'Konfigurasi rahasia foto tidak valid atau tidak privat. Jalankan photos:setup.';
        clearstatcache(true, $path);
        $stat = @lstat($path);
        if ($stat === false || ($stat['mode'] & 0170000) !== 0100000
            || ($stat['mode'] & 07777) !== 0600 || $stat['size'] < 1 || $stat['size'] > 4096) {
            throw new \RuntimeException($invalid);
        }
        $handle = @fopen($path, 'rb');
        if ($handle === false) {
            throw new \RuntimeException($invalid);
        }
        try {
            $opened = @fstat($handle);
            if ($opened === false || $opened['ino'] !== $stat['ino'] || $opened['dev'] !== $stat['dev']
                || ($opened['mode'] & 0177777) !== 0100600) {
                throw new \RuntimeException($invalid);
            }
            $bytes = @stream_get_contents($handle, 4097);
        } finally {
            fclose($handle);
        }
        $data = is_string($bytes) ? json_decode($bytes, true, 4) : null;
        if (! is_array($data) || json_last_error() !== JSON_ERROR_NONE) {
            throw new \RuntimeException($invalid);
        }
        foreach (['service_token', 'encryption_key'] as $field) {
            if (! is_string($data[$field] ?? null) || preg_match('/\A[a-f0-9]{64}\z/D', $data[$field]) !== 1) {
                throw new \RuntimeException($invalid);
            }
        }
        return $data;
    }
}